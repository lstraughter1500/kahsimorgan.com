import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import worker from '../server/worker.mjs';
const source = await readFile(new URL('../basketball-schedule.js', import.meta.url), 'utf8');
const url = 'https://kahsimorgan.com/api/attendance/2026-12-04-logan';
const visitor = '00000000-0000-4000-8000-000000000001';
const request = (body = '{"going":true}') => new Request(url, { method: 'PUT', headers: { Origin: 'https://kahsimorgan.com', 'X-Visitor-ID': visitor, 'Content-Type': 'application/json' }, body });
const assets = { fetch: async () => new Response(source) };
assert.equal((await worker.fetch(request(), { ASSETS: assets })).status, 503);
let mutations = 0;
const db = { prepare() { return { bind() { return this; }, first() { throw Error('Database offline'); } }; }, batch() { mutations++; } };
const env = { ASSETS: assets, ATTENDANCE_DB: db, ATTENDANCE_LIMITER: { limit: async () => ({ success: false }) } };
const limited = await worker.fetch(request(), env);
assert.equal(limited.status, 429);
assert.equal(limited.headers.get('Retry-After'), '60');
assert.equal(mutations, 0);
assert.equal((await worker.fetch(request('x'.repeat(129)), env)).status, 413);
assert.equal((await worker.fetch(request('broken json'), env)).status, 400);
const read = new Request(url, { headers: { 'X-Visitor-ID': visitor } });
const unavailable = await worker.fetch(read, env);
assert.equal(unavailable.status, 503);
assert.equal((await unavailable.json()).going, undefined);
assert.equal((await worker.fetch(new Request('https://kahsimorgan.com/api/unknown'), env)).status, 404);
const asset = await worker.fetch(new Request('https://kahsimorgan.com/'), env);
assert.equal(await asset.text(), source);
console.log('PASS: throttled mutations never reach D1; missing database, database errors, invalid/oversized bodies and static asset fallback are handled safely.');
