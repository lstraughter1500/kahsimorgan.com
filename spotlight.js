(() => {
  const section = document.getElementById('spotlight');
  if (!section) return;
  // Add each new feature as a .spotlight-card in the HTML; both views use that list.
  const articles = [...section.querySelectorAll('.spotlight-card')];
  if (!articles.length) return;
  const opener = document.createElement('button');
  opener.type = 'button';
  opener.className = 'spotlight-carousel';
  opener.setAttribute('aria-label', 'View all Spotlight articles and media features');
  opener.setAttribute('aria-haspopup', 'dialog');
  const track = document.createElement('span');
  track.className = 'spotlight-track';
  track.setAttribute('aria-hidden', 'true');
  const group = document.createElement('span');
  group.className = 'spotlight-track-group';
  articles.forEach(article => {
    const tile = document.createElement('span');
    tile.className = 'spotlight-tile';
    const photo = article.querySelector('img').cloneNode();
    photo.alt = '';
    const source = document.createElement('span');
    source.className = 'spotlight-tile-source';
    source.textContent = article.querySelector('.spotlight-source').textContent;
    const title = document.createElement('span');
    title.className = 'spotlight-tile-title';
    title.textContent = article.querySelector('h3').textContent;
    const copy = document.createElement('span');
    copy.className = 'spotlight-tile-copy';
    const summary = document.createElement('span');
    summary.className = 'spotlight-tile-summary';
    summary.textContent = article.querySelector('.spotlight-copy > p:not([class])').textContent;
    copy.append(source, title, summary);
    tile.append(photo, copy);
    group.append(tile);
  });
  track.append(group);
  track.style.animationDuration = `${Math.max(56, articles.length * 28)}s`;
  const rotating = articles.length > 1;
  if (rotating) track.append(group.cloneNode(true));
  else section.classList.add('spotlight-single');
  opener.append(track);
  const controls = document.createElement('div');
  controls.className = 'thanks-controls spotlight-controls';
  const hint = document.createElement('span');
  hint.textContent = 'Tap to explore all articles, posts, and media features.';
  const motion = document.createElement('button');
  motion.type = 'button';
  motion.className = 'thanks-motion';
  motion.textContent = 'Pause motion';
  motion.setAttribute('aria-pressed', 'false');
  motion.hidden = !rotating;
  controls.append(hint, motion);
  const dialog = document.createElement('dialog');
  dialog.className = 'highlights-dialog spotlight-dialog';
  dialog.setAttribute('aria-labelledby', 'spotlight-dialog-title');
  const header = document.createElement('div');
  header.className = 'highlights-dialog-header';
  const heading = document.createElement('h2');
  heading.id = 'spotlight-dialog-title';
  heading.textContent = 'Kahsi in the Spotlight';
  const close = document.createElement('button');
  close.type = 'button';
  close.className = 'button secondary';
  close.textContent = 'Close';
  header.append(heading, close);
  const list = document.createElement('div');
  list.className = 'spotlight-all';
  articles.forEach(article => list.append(article));
  dialog.append(header, list);
  section.append(opener, controls, dialog);
  motion.addEventListener('click', () => {
    const paused = section.classList.toggle('spotlight-paused');
    motion.setAttribute('aria-pressed', String(paused));
    motion.textContent = paused ? 'Resume motion' : 'Pause motion';
  });
  opener.addEventListener('click', () => {
    dialog.showModal();
    section.classList.add('spotlight-modal-open');
    document.body.classList.add('spotlight-dialog-open');
    close.focus();
  });
  close.addEventListener('click', () => dialog.close());
  dialog.addEventListener('click', event => {
    if (event.target !== dialog) return;
    const r = dialog.getBoundingClientRect();
    if (event.clientX < r.left || event.clientX > r.right || event.clientY < r.top || event.clientY > r.bottom) dialog.close();
  });
  dialog.addEventListener('close', () => {
    section.classList.remove('spotlight-modal-open');
    document.body.classList.remove('spotlight-dialog-open');
    opener.focus();
  });
})();
